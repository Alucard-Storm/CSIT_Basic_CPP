// Anatomy of a C++ program: comments, header, namespace, main.
#include <iostream>
using namespace std;

int main() {
    cout << "Line one" << endl;
    cout << "Line two\n";               // \n also starts a new line
    cout << "Tab\tseparated\tvalues\n"; // \t is a tab
    cout << "She said \"hi\"" << endl;  // \" prints a quote
    return 0;
}
